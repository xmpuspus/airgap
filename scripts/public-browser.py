def digest(file):
    return hashlib.sha256(pathlib.Path(file).read_bytes()).hexdigest()


def write_json(file, value):
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n")


def code_identity():
    files = json.loads((ROOT / "validation/public-service-lineage.json").read_text())
    return {file: digest(ROOT / file) for file in files}


def committed_source():
    commit = subprocess.check_output(
        ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True
    ).strip()
    # These two outputs are generated by an actual model run after source commit.
    # Their exact bytes remain mandatory in the capture lineage and report checks.
    generated = {
        "web/data/public-service.json",
        "evidence/public-service/experiment.json",
    }
    committed = {}
    for file, sha in code_identity().items():
        if file in generated:
            continue
        saved = subprocess.run(
            ["git", "show", f"{commit}:{file}"], cwd=ROOT, capture_output=True
        )
        require(
            saved.returncode == 0 and hashlib.sha256(saved.stdout).hexdigest() == sha,
            f"Commit reviewed source before capture: {file}",
        )
        committed[file] = sha
    return commit, committed


def probe(file):
    return json.loads(
        subprocess.check_output(
            [
                "ffprobe",
                "-v",
                "error",
                "-show_streams",
                "-show_format",
                "-of",
                "json",
                str(file),
            ]
        )
    )


def downloaded(page, selector, expected_file, validate):
    with page.expect_download() as event:
        page.locator(selector).click()
    download = event.value
    target = OUT / expected_file
    download.save_as(target)
    payload = json.loads(target.read_text())
    validate(payload)
    return {
        "path": str(target.relative_to(ROOT)),
        "sha256": digest(target),
        "bytes": target.stat().st_size,
    }


def require(condition, message):
    if not condition:
        raise AssertionError(message)


def answer_case(page, case):
    page.locator("#case").select_option(case["id"])
    page.locator("#ask-form button[type=submit]").click()
    expected_path = case.get(
        "expectPath",
        "refusal"
        if case.get("expectRefusal")
        else "unavailable"
        if case.get("expectTool")
        else "record",
    )
    expect(page.locator("#route")).to_have_text(
        f"Route: {expected_path} · Model called: no"
    )
    actual = page.locator("#answer").inner_text()
    for phrase in case.get("mustInclude", []):
        require(phrase.lower() in actual.lower(), f"{case['id']}: missing {phrase}")
    for phrase in case.get("mustExclude", []):
        require(
            phrase.lower() not in actual.lower(), f"{case['id']}: forbidden {phrase}"
        )
    return {
        "id": case["id"],
        "query": case["query"],
        "answer": actual,
        "routeLabel": page.locator("#route").inner_text(),
    }


def model_row(variant):
    return (
        '#experiment-outputs > details[data-question="nbi"]'
        f'[data-variant="{variant}"][data-repetition="1"]'
    )


def assert_readable(page, width):
    require(
        page.evaluate("document.documentElement.scrollWidth - innerWidth") <= 1,
        f"{width}px document overflow",
    )
    for locator in page.locator("#experiment-summary .metric-card").all():
        require(
            locator.evaluate("(el) => el.scrollWidth <= el.clientWidth + 1"),
            "Metric card clips content",
        )
        for item in locator.locator("dt, dd").all():
            require(
                item.evaluate(
                    "(el) => {const r=el.getBoundingClientRect(); "
                    "return r.left>=0 && r.right<=innerWidth;}"
                ),
                "Metric lies outside viewport",
            )
    for locator in page.locator(".raw-output:visible, .hash:visible").all():
        require(
            locator.evaluate("(el) => parseFloat(getComputedStyle(el).fontSize) >= 14"),
            "Evidence text is too small",
        )


