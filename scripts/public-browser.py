def capture(browser, base, pack, source_commit, committed_files):
    require(
        pack["experiment"] is not None and len(pack["experiment"]["rows"]) == 54,
        "Model experiment NOT RUN; capture requires all 54 rows",
    )
    recordings = []
    run_id = (
        datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ") + "-" + uuid4().hex[:8]
    )
    raw_dir = RAW / run_id
    raw_dir.mkdir(parents=True, exist_ok=True)
    release = ROOT / "demo/public-service"
    staged = prepare_release(release, raw_dir)
    initial_identity = code_identity()
    for feature in FEATURES:
        context = browser.new_context(
            viewport={"width": 1280, "height": 900},
            record_video_dir=str(raw_dir),
            record_video_size={"width": 1280, "height": 900},
            accept_downloads=True,
        )
        page = context.new_page()
        start = time.monotonic()
        beats = []

        def beat(label, selector):
            page.locator(selector).evaluate(
                '(el) => el.scrollIntoView({behavior:"smooth", block:"center"})'
            )
            page.wait_for_timeout(700)
            active = page.locator("[data-view][aria-current=page]").get_attribute(
                "data-view"
            )
            route = (
                page.locator(
                    "#historical-route" if active == "workbench" else "#route"
                ).inner_text()
                if active in ["ask", "workbench"]
                else active
            )
            # Impact checks can run before an answer is displayed in this view.
            # Record that observed empty state explicitly, without inventing a route.
            route = route or "no_displayed_answer"
            beats.append(
                {
                    "label": label,
                    "observedAtSeconds": time.monotonic() - start,
                    "visibleText": page.locator(selector).inner_text(),
                    "route": route,
                    "modelCalledDuringCapture": False,
                    "recordedResults": active == "experiment",
                }
            )
            page.wait_for_timeout(
                5000
            )  # Uncut, readable observation of the actual running UI.

        page.goto(base + "/lab.html", wait_until="networkidle")
        expect(page.locator("#workspace")).to_be_visible()
        if feature == "replay-pack":
            page.locator("#replay").click()
            expect(page.locator("#replay-status")).to_contain_text("passed")
            beat("Sequential real replay", "#replay-status")
            downloaded(
                page,
                "#export-replay",
                f"capture-{feature}.json",
                lambda data: require(
                    all(row["passed"] for row in data["cases"]), "Capture replay failed"
                ),
            )
            beat(
                "Actual replay downloaded; last case shown",
                "#replay-results li:last-child",
            )
        elif feature == "evidence-lab":
            page.locator("#case").select_option("gov-2")
            page.locator("#ask-form button[type=submit]").click()
            beat("Selected Filipino case answered by shared code", ".answer-panel")
            page.locator("#clear").click()
            page.locator("#question").fill("Magkano ang passport?")
            page.locator("#ask-form button[type=submit]").click()
            beat("Live deterministic fee answer", ".answer-panel")
            page.locator("#doubt").click()
            page.locator("#sources summary").first.click()
            beat("Actual doubt and source", ".answer-panel")
            downloaded(
                page,
                "#export-case",
                f"capture-{feature}.json",
                lambda data: require(
                    data["modelCalled"] is False, "Live model label mismatch"
                ),
            )
        elif feature == "source-workbench":
            page.locator("[data-view=workbench]").click()
            page.locator("#check-impact").click()
            beat("Affected historical questions checked", "#impact-results")
            page.locator("#load-original").click()
            page.locator("#historical-form button").click()
            beat("Original historical answer", "#historical-answer")
            page.locator("#reviewed").check()
            page.locator("#apply").click()
            page.locator("#historical-form button").click()
            beat("Amended historical answer", "#historical-answer")
            page.locator("#rollback").click()
            page.locator("#historical-form button").click()
            beat("Rollback answer", "#historical-answer")
        elif feature == "model-controls":
            page.locator("[data-view=experiment]").click()
            beat(
                "Actual recorded experiment identity and denominators",
                "#experiment-summary",
            )
            retrieved = model_row("retrieved-model")
            controlled = model_row("application-controls")
            rows = {
                row["variant"]: row
                for row in pack["experiment"]["rows"]
                if row["questionId"] == "nbi" and row["repetition"] == 1
            }
            retrieved_stop = rows["retrieved-model"]["stopReason"]
            controlled_stop = rows["application-controls"]["stopReason"]
            page.locator(retrieved + " > summary").click()
            beat(
                f"Recorded NBI model response; stop reason {retrieved_stop}",
                retrieved + " .raw-output",
            )
            page.locator(controlled + " > summary").click()
            beat(
                f"Recorded controlled NBI response; stop reason {controlled_stop}",
                controlled + " .raw-output",
            )
            beat(
                "Application used the complete source-record fallback"
                if rows["application-controls"]["fallback"]
                else "Application accepted the model output",
                controlled + " .displayed-answer",
            )
        else:
            page.locator("[data-view=kit]").click()
            beat("Reproduction command and code identity", "#view-kit")
            downloaded(
                page,
                "#export-pack",
                f"capture-{feature}.json",
                lambda data: require(
                    data["coreSha256"] == pack["coreSha256"],
                    "Wrong code identity exported",
                ),
            )
            beat("Public source pack exported", "#view-kit")
        video = page.video
        require(video is not None, "Browser did not create a real video artifact")
        context.close()
        raw_file = pathlib.Path(video.path())
        media = probe(raw_file)
        duration = float(media["format"]["duration"])
        require(
            all(
                0 <= item["observedAtSeconds"] <= duration + 1
                and item["visibleText"]
                and item["route"]
                and item["modelCalledDuringCapture"] is False
                for item in beats
            ),
            f"Incomplete observed beat metadata: {feature}",
        )
        target = staged / f"{feature}.gif"
        mp4 = target.with_suffix(".mp4")
        subprocess.run(
            [
                "ffmpeg",
                "-y",
                "-v",
                "error",
                "-i",
                str(raw_file),
                "-an",
                "-c:v",
                "libx264",
                "-pix_fmt",
                "yuv420p",
                "-movflags",
                "+faststart",
                str(mp4),
            ],
            check=True,
        )
        subprocess.run(
            [
                "ffmpeg",
                "-y",
                "-v",
                "error",
                "-i",
                str(raw_file),
                "-filter_complex",
                "[0:v]fps=10,scale=960:-1:flags=lanczos,split[a][b];[a]palettegen=max_colors=64[p];[b][p]paletteuse=dither=bayer",
                "-loop",
                "0",
                str(target),
            ],
            check=True,
        )
        for exported in (target, mp4):
            actual = probe(exported)
            require(
                int(actual["streams"][0]["width"]) >= 900,
                f"Export too small: {exported.name}",
            )
            require(
                abs(float(actual["format"]["duration"]) - duration) < 0.25,
                f"Export duration changed: {exported.name}",
            )
        sheet = raw_dir / f"{feature}-frames.jpg"
        subprocess.run(
            [
                "ffmpeg",
                "-y",
                "-v",
                "error",
                "-i",
                str(target),
                "-vf",
                f"fps=1/{max(duration / 6, 0.1)},scale=480:-1,tile=3x2",
                "-frames:v",
                "1",
                str(sheet),
            ],
            check=True,
        )
        write_json(raw_dir / f"{feature}-beats.json", beats)
        recordings.append(
            {
                "feature": feature,
                "output": str((release / target.name).relative_to(ROOT)),
                "sha256": digest(target),
                "shareMp4": str((release / mp4.name).relative_to(ROOT)),
                "shareMp4Sha256": digest(mp4),
                "source": str(raw_file.relative_to(ROOT)),
                "sourceSha256": digest(raw_file),
                "contactSheet": str(sheet.relative_to(ROOT)),
                "durationSeconds": duration,
                "playbackSpeed": 1,
                "editRangesSeconds": [[0, duration]],
                "omittedSourceRangesSeconds": [],
                "browser": browser.version,
                "device": "Playwright desktop viewport 1280x900",
                "evidenceClass": "browser-runtime",
                "provider": "shared-deterministic-core",
                "modelView": "recorded-host-results"
                if feature == "model-controls"
                else None,
                "coreSha256": pack["coreSha256"],
                "corpusSha256": pack["corpusSha256"],
                "modelSha256": pack["experiment"]["model"]["sha256"],
                "beats": beats,
                "loopReviewed": False,
                "timingMethod": (
                    "Monotonic observations relative to new_page return; "
                    "uncut video duration measured by ffprobe"
                ),
            }
        )
    manifest = {
        "schemaVersion": 1,
        "capturedAt": datetime.now(timezone.utc).isoformat(),
        "playwright": importlib.metadata.version("playwright"),
        "host": {
            "system": platform.system(),
            "release": platform.release(),
            "arch": platform.machine(),
        },
        "codeFiles": initial_identity,
        "committedFiles": committed_files,
        "sourceCommit": source_commit,
        "sourceState": (
            "Committed source and knowledge; generated model report "
            "and browser pack identified by exact hashes"
        ),
        "captureCommand": shlex.join(
            [
                pathlib.Path(sys.executable).name,
                *(["-B"] if sys.dont_write_bytecode else []),
                str(pathlib.Path(sys.argv[0]).resolve().relative_to(ROOT)),
                *sys.argv[1:],
            ]
        ),
        "recordings": recordings,
    }
    require(
        code_identity() == initial_identity,
        "Source changed during capture; staged files retained, "
        "previous release preserved",
    )
    require(
        committed_source() == (source_commit, committed_files),
        "Commit changed during capture",
    )
    write_json(staged / "recordings.json", manifest)
    descriptions = {
        "replay-pack": (
            "Replay Pack",
            "Runs 21 authored checks in order, with no model call.",
        ),
        "evidence-lab": (
            "Evidence Lab",
            "Answers a Filipino question, rechecks its source, and downloads evidence.",
        ),
        "source-workbench": (
            "Source Workbench",
            "Applies the actual 2024 holiday amendment and rolls it back.",
        ),
        "model-controls": (
            "Model Controls",
            "Compares actual recorded NBI model outputs "
            "with the answer the application displays.",
        ),
        "demo-kit": (
            "Demo Kit",
            "Shows the reproduction command, code identity, and exported source pack.",
        ),
    }
    index = [
        "# Actual public-service browser captures",
        "",
        "Each clip records a browser run. Inspect each full loop "
        "and its screenshots before publication.",
        "",
        "| Feature | What the clip shows | GIF | MP4 |",
        "| --- | --- | --- | --- |",
    ]
    for recording in recordings:
        feature = recording["feature"]
        label, description = descriptions[feature]
        index.append(
            f"| {label} | {description} | [GIF]({feature}.gif) | [MP4]({feature}.mp4) |"
        )
    index.extend(
        [
            "",
            "[Manifest](recordings.json) records hashes, observed beats "
            "and uncut edit ranges.",
            "Raw footage remains ignored under tmp/recordings. "
            "No native run is implied.",
            "",
        ]
    )
    (staged / "README.md").write_text("\n".join(index))
    for name in ("recordings.json", "README.md"):
        formatted = subprocess.check_output(
            [
                "node",
                "node_modules/prettier/bin-prettier.js",
                "--stdin-filepath",
                f"demo/public-service/{name}",
            ],
            input=(staged / name).read_bytes(),
            cwd=ROOT,
        )
        (staged / name).write_bytes(formatted)
    promote_release(staged, release, raw_dir)
    return manifest


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--capture", action="store_true")
    args = parser.parse_args()
    source_commit, committed_files = (
        committed_source() if args.capture else (None, None)
    )
    require(
        importlib.metadata.version("playwright") == "1.58.0",
        "Install scripts/public-requirements.txt",
    )
    OUT.mkdir(parents=True, exist_ok=True)
    pack = json.loads((ROOT / "web/data/public-service.json").read_text())
    require(
        pack["experiment"]
        == json.loads((ROOT / "evidence/public-service/experiment.json").read_text()),
        "Pack has stale model results; run public:build",
    )
    require(
        pack["coreSha256"] == digest(ROOT / "src/core/publicService.ts"),
        "Pack has stale core; run public:build",
    )
    require(
        pack["experiment"]["coreSha256"] == pack["coreSha256"],
        "Recorded experiment used a different core; rerun actual experiment",
    )
    require(
        pack["experiment"]["corpusSha256"] == pack["corpusSha256"],
        "Recorded experiment used different records",
    )
    require(
        pack["experiment"]["runnerSha256"]
        == digest(ROOT / "scripts/public-experiment.mjs"),
        "Recorded experiment used a different runner",
    )
    handler = functools.partial(
        http.server.SimpleHTTPRequestHandler, directory=str(ROOT / "web")
    )
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    try:
        with sync_playwright() as playwright:
            browser = playwright.chromium.launch(headless=True)
            try:
                base = f"http://127.0.0.1:{server.server_port}"
                qa(browser, base, pack)
                if args.capture:
                    capture(browser, base, pack, source_commit, committed_files)
            finally:
                browser.close()
    finally:
        server.shutdown()
        server.server_close()
    print(
        "Real browser journey passed. Screenshots and loops "
        "still require independent visual inspection."
    )


if __name__ == "__main__":
    main()
